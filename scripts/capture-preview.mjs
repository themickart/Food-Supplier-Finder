import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const output = fileURLToPath(new URL('../artifacts/', import.meta.url))
await mkdir(output, { recursive: true })
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
await page.goto(process.env.PREVIEW_URL || 'http://127.0.0.1:8000')
await page.getByRole('button', { name: /Деморежим/ }).click()
await page.getByRole('button', { name: 'Таблица', exact: true }).click()
await page.locator('.supplier-table tbody tr').first().waitFor()
await page.screenshot({ path: output + '/catalog-desktop.png' })
await page.getByRole('button', { name: 'Фильтры', exact: true }).click()
await page.screenshot({ path: output + '/filters-desktop.png', fullPage: true })
await page.getByRole('button', { name: 'Закрыть фильтры', exact: true }).click()
await page.locator('.rating-button').first().click()
await page.screenshot({ path: output + '/rating-explained.png', fullPage: false })
await page.getByRole('button', { name: 'Закрыть окно' }).click()
await page.getByRole('button', { name: 'Карточки', exact: true }).click()
await page.screenshot({ path: output + '/catalog-cards.png' })
await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
await page.screenshot({ path: output + '/supplier-detail.png' })
await page.getByRole('tab', { name: 'Условия и доставка' }).click()
await page.getByLabel('Количество для расчёта').fill('150')
await page.locator('.position-calculator').scrollIntoViewIfNeeded()
await page.screenshot({ path: output + '/position-calculator.png' })
await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
await page.getByRole('textbox', { name: 'Личная заметка' }).fill('  =1+1')
await page.getByRole('button', { name: 'Сохранить заметку', exact: true }).click()
await page.getByRole('button', { name: 'Закрыть окно' }).click()
await page.getByRole('checkbox', { name: 'Выбрать: Молочный маршрут', exact: true }).check()
await page.locator('.selection-line').evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + window.scrollY + 200))
await page.screenshot({ path: output + '/selected-sticky.png' })
for (const format of ['CSV', 'XLSX']) {
  await page.locator('.bulk-actions').getByRole('button', { name: 'Выгрузить выбранное', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Включить мои заметки' }).check()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: `Скачать ${format}`, exact: true }).click()
  await (await download).saveAs(output + `/pages-demo-suppliers.${format.toLowerCase()}`)
}
await page.getByRole('button', { name: 'Снять выбор', exact: true }).click()
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(300)
await page.evaluate(() => window.scrollTo(0, 0))
await page.screenshot({ path: output + '/catalog-mobile-viewport.png' })
await page.screenshot({ path: output + '/catalog-mobile.png', fullPage: true })
await browser.close()
console.log('Preview screenshots: artifacts/catalog-desktop.png, supplier-detail.png, catalog-mobile.png')
