import { expect, test } from '@playwright/test'

test.skip(!process.env.PLAYWRIGHT_STANDALONE, 'Only the standalone Pages build')

test('Pages works without backend calls and browser catalogue survives reload with edit history', async ({ page, browser }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.route('**/api/**', route => route.abort())
  await page.goto('./')
  await expect(page.locator('.hosting-notice')).toContainText('Общей серверной базы здесь нет')
  await page.locator('.heading-actions').getByRole('button', { name: 'Добавить поставщика', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название компании').fill('Локальная тестовая компания')
  await dialog.getByLabel('URL источника').fill('https://supplier-test.ru/contacts')
  await dialog.getByLabel('Официальный сайт').fill('https://supplier-test.ru')
  await dialog.getByLabel('Адрес', { exact: true }).fill('Первый адрес')
  await dialog.getByRole('button', { name: 'Добавить в каталог', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Локальная тестовая компания', exact: true }).click()
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('Адрес', { exact: true }).fill('Новый адрес')
  await dialog.getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Новый адрес')
  await page.getByRole('tab', { name: 'Источники', exact: true }).click()
  await page.getByText('Предыдущие значения до изменения', { exact: true }).click()
  await expect(page.locator('.source-history')).toContainText('Первый адрес')
  expect(requests).toEqual([])
  const isolated = await browser.newContext()
  const other = await isolated.newPage()
  await other.goto(page.url())
  await expect(other.getByRole('button', { name: 'Локальная тестовая компания', exact: true })).toHaveCount(0)
  await isolated.close()
})

test('blocked browser catalogue writes are errors and never successful imports', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('blocked', 'QuotaExceededError') } })
  await page.goto('./')
  await page.locator('.heading-actions').getByRole('button', { name: 'Добавить поставщика', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название компании').fill('Не сохранится')
  await dialog.getByLabel('URL источника').fill('https://supplier-test.ru/contacts')
  await dialog.getByRole('button', { name: 'Добавить в каталог', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('не сохранил каталог')
  await expect(dialog).toBeVisible()
})
