import { expect, test } from '@playwright/test'

test('cards come first; wheel over the table scrolls the page and selected actions stick', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await expect(page.locator('.supplier-card')).toHaveCount(12)
  await expect(page.locator('.view-switch button').first()).toHaveAttribute('aria-label', 'Карточки')
  await page.getByRole('button', { name: 'Таблица', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Выбрать: Молочный маршрут', exact: true }).check()
  const selection = page.locator('.selection-line.has-selection')
  await selection.evaluate(el => window.scrollTo(0, el.getBoundingClientRect().top + window.scrollY - 90))
  const table = page.locator('.supplier-table-wrap')
  const bounds = await table.boundingBox()
  expect(bounds).not.toBeNull()
  await page.mouse.move(Math.min(bounds!.x + 150, 300), Math.min(bounds!.y + 180, 600))
  const before = await page.evaluate(() => window.scrollY)
  await page.mouse.wheel(0, 400)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(before + 100)
  await expect.poll(async () => Math.abs((await selection.boundingBox())!.y)).toBeLessThan(2)
  await expect(selection.getByRole('button', { name: 'Выгрузить выбранное' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(async () => (await selection.boundingBox())!.y).toBeGreaterThan(150)
})

test('calculator uses price units, minimum and explicit rounding; old brand is recoverable', async ({ page }) => {
  await page.goto('./')
  await expect(page).toHaveTitle(/FSUP/)
  if (await page.getByRole('button', { name: 'Открыть меню', exact: true }).isVisible()) {
    await page.getByRole('button', { name: 'Открыть меню', exact: true }).click()
    await page.getByRole('button', { name: 'О сервисе и хранении', exact: true }).click()
  } else await page.getByRole('button', { name: 'О сервисе', exact: true }).click()
  await page.getByRole('button', { name: 'Вернуть «Поставку»', exact: true }).click()
  await expect(page).toHaveTitle(/Поставка/)
  await page.getByRole('button', { name: 'FSUP', exact: true }).click()
  await expect(page).toHaveTitle(/FSUP/)
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  if (await page.locator('.sidebar-backdrop').isVisible()) await page.getByRole('button', { name: 'Закрыть меню', exact: true }).click()
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Сырная мастерская', exact: true }).click()
  await page.getByRole('tab', { name: 'Условия и доставка' }).click()
  const calculator = page.getByRole('region', { name: 'Калькулятор позиции' })
  await calculator.getByLabel('Количество для расчёта').fill('5')
  await expect(calculator.locator('.calculator-result')).toContainText('2 950')
  await expect(calculator.locator('.calculator-result')).toContainText('Ниже минимума')
  await calculator.getByLabel('Количество для расчёта').fill('11')
  await calculator.getByLabel('Округлить до кратности закупки').check()
  await calculator.getByLabel('Кратность закупки').fill('5')
  await expect(calculator.locator('.calculator-result')).toContainText('8 850')
  await expect(calculator.locator('.calculator-result')).toContainText('минимум достигнут')
  await expect(calculator).toContainText('Доставка, скидки, налоги')
})
