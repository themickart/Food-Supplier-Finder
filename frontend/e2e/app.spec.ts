import { expect, test } from '@playwright/test'

test('demo search, favorites and notes survive reload; CSV/XLSX work', async ({ page, browser }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Каталог поставщиков' })).toBeVisible()
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Карточки', exact: true }).click()
  await expect(page.locator('.supplier-card')).toHaveCount(12)
  await expect(page.locator('.demo-banner')).toContainText('вымышлены')
  await page.getByRole('textbox', { name: 'Товар или компания' }).fill('Моцарелла')
  await page.getByLabel('Регион поиска').selectOption('Екатеринбург')
  await page.getByRole('button', { name: 'Найти поставщиков', exact: true }).click()
  await expect(page.locator('.supplier-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Добавить в избранное: Молочный маршрут', exact: true }).click()
  await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
  await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('textbox', { name: 'Личная заметка' }).fill('Запросить прайс на 20 кг')
  await page.getByRole('button', { name: 'Сохранить заметку', exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
  await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
  await expect(page.getByRole('textbox', { name: 'Личная заметка' })).toHaveValue('Запросить прайс на 20 кг')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'В избранном', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.getByRole('checkbox', { name: 'Выбрать: Молочный маршрут', exact: true }).check()
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Включить мои заметки' }).check()
  const csv = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать CSV', exact: true }).click()
  expect((await csv).suggestedFilename()).toBe('demo-suppliers.csv')
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click()
  const xlsx = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать XLSX', exact: true }).click()
  expect((await xlsx).suggestedFilename()).toBe('demo-suppliers.xlsx')
  await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
  await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
  await page.getByRole('textbox', { name: 'Личная заметка' }).fill('Обновлённая заметка')
  await page.getByRole('button', { name: 'Сохранить заметку', exact: true }).click()
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
  await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
  await expect(page.getByRole('textbox', { name: 'Личная заметка' })).toHaveValue('Обновлённая заметка')
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Личная заметка' })).toHaveValue('')
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  if (await page.getByRole('button', { name: 'Открыть меню', exact: true }).isVisible()) await page.getByRole('button', { name: 'Открыть меню', exact: true }).click()
  await page.locator('.main-nav').getByRole('button', { name: /^История поиска/ }).click()
  await expect(page.locator('.history-row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Очистить историю', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Пока без истории' })).toBeVisible()
  const otherBrowserProfile = await browser.newContext()
  const otherPage = await otherBrowserProfile.newPage()
  await otherPage.goto('./')
  expect(await otherPage.evaluate(() => localStorage.getItem('postavka.personal.v1'))).toBeNull()
  await otherBrowserProfile.close()
  expect(errors).toEqual([])
})

