test('real import from demo returns to real catalogue; duplicate is merged', async ({ page }) => {
  const name = `Тестовая запись ${Date.now()}`
  const website = `https://e2e-${Date.now()}.ru`
  await page.goto('./')
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.locator('.heading-actions').getByRole('button', { name: 'Добавить поставщика', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название компании').fill(name)
  await dialog.getByLabel('URL источника').fill(website + '/contacts')
  await dialog.getByLabel('Официальный сайт').fill(website)
  await dialog.getByLabel('Город', { exact: true }).fill('Екатеринбург')
  await dialog.getByRole('button', { name: 'Добавить в каталог' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Реальный каталог|Локальный каталог/ })).toHaveClass('active')
  await expect(page.getByRole('button', { name, exact: true })).toBeVisible()
  await page.getByRole('button', { name, exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Не проверено')
  await page.getByRole('tab', { name: 'Источники', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText(website + '/contacts')
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.locator('.heading-actions').getByRole('button', { name: 'Добавить поставщика', exact: true }).click()
  await dialog.getByLabel('Название компании').fill(name)
  await dialog.getByLabel('URL источника').fill(website + '/contacts')
  await dialog.getByLabel('Официальный сайт').fill(website)
  await dialog.getByRole('button', { name: 'Добавить в каталог' }).click()
  await expect(page.getByRole('status')).toContainText('Найден дубликат')
  await expect(page.getByRole('button', { name, exact: true })).toHaveCount(1)
})

test('catalog network errors have a working retry', async ({ page }) => {
  test.skip(Boolean(process.env.PLAYWRIGHT_STANDALONE), 'Pages has no API requests')
  await page.route('**/api/v1/suppliers?**', route => route.abort())
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить каталог' })).toBeVisible()
  await page.unroute('**/api/v1/suppliers?**')
  await page.getByRole('button', { name: 'Повторить', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить каталог' })).toHaveCount(0)
  await expect(page.locator('.supplier-card, .supplier-table tbody tr').first()).toBeVisible()
})

test('blocked browser storage does not claim a successful note save', async ({ page }) => {
  await page.addInitScript(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Storage disabled', 'QuotaExceededError') }
  })
  await page.goto('./')
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Молочный маршрут', exact: true }).click()
  await page.getByRole('tab', { name: 'Заметки и письмо' }).click()
  await page.getByRole('textbox', { name: 'Личная заметка' }).fill('Эта заметка не сохранится')
  await page.getByRole('button', { name: 'Сохранить заметку', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Браузер не сохранил заметку')
  await expect(page.getByRole('dialog').getByRole('status')).not.toContainText('Заметка сохранена')
})
