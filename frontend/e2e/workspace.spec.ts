import { expect, test, type Page } from '@playwright/test'

async function demo(page: Page) {
  await page.goto('./')
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Таблица', exact: true }).click()
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(12)
}
async function navigate(page: Page, name: RegExp | string) {
  if (await page.getByRole('button', { name: 'Открыть меню', exact: true }).isVisible()) await page.getByRole('button', { name: 'Открыть меню', exact: true }).click()
  await page.locator('.main-nav').getByRole('button', { name }).click()
}

test('rating has an accessible explanation and layouts are interactive', async ({ page }) => {
  await demo(page)
  await page.locator('.rating-button').first().click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Из чего складывается оценка' })).toBeVisible()
  await expect(dialog).toContainText('а не надёжность компании')
  await expect(dialog.locator('.rating-criterion')).toHaveCount(7)
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.getByRole('button', { name: 'Действия: Белая полка', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Личная заметка', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Личная заметка' })).toBeVisible()
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  await page.getByRole('button', { name: 'Карточки', exact: true }).click()
  await expect(page.locator('.supplier-card')).toHaveCount(12)
  await page.locator('.supplier-card').first().getByRole('button', { name: 'Карточка', exact: true }).click()
  await page.getByRole('tab', { name: 'Условия и доставка' }).click()
  await expect(page.getByRole('dialog')).toContainText('Фасовка')
  await page.getByRole('tab', { name: 'Источники', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('учебный адрес')
  await page.getByRole('button', { name: 'Закрыть окно' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('advanced filters, presets and export use the same conditions', async ({ page }) => {
  await demo(page)
  await page.getByRole('button', { name: 'Фильтры', exact: true }).click()
  const filters = page.getByRole('form', { name: 'Расширенные фильтры' })
  await filters.getByLabel('Товар для цены', { exact: true }).fill('моцарелла')
  await filters.getByLabel('Единица цены', { exact: true }).selectOption('кг')
  await filters.getByLabel('Цена от', { exact: true }).fill('500')
  await filters.getByLabel('Цена до', { exact: true }).fill('700')
  await filters.getByRole('button', { name: 'Применить фильтры', exact: true }).click()
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.supplier-table')).toContainText('Сырная мастерская')
  await page.getByRole('button', { name: 'Сохранить поиск', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Название набора').fill('Сыр по килограммам')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить набор', exact: true }).click()
  await page.getByRole('button', { name: 'Сбросить всё', exact: true }).click()
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(12)
  await page.getByRole('button', { name: 'Сыр по килограммам', exact: true }).click()
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(1)
  await page.reload()
  await page.getByRole('button', { name: /Деморежим/ }).click()
  await page.getByRole('button', { name: 'Сыр по килограммам', exact: true }).click()
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('выдача (1)')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать XLSX', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('demo-suppliers.xlsx')
})

test('bulk favorites, column settings and readiness are real actions', async ({ page }, info) => {
  await demo(page)
  if (info.project.name === 'desktop') {
    await page.getByRole('button', { name: 'Настроить столбцы', exact: true }).click()
    await page.getByRole('dialog').getByRole('checkbox', { name: 'Контакты', exact: true }).check()
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    await expect(page.locator('.supplier-table thead')).toContainText('Контакты')
  }
  await page.getByRole('checkbox', { name: 'Выбрать: Молочный маршрут', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Выбрать: Сырная мастерская', exact: true }).check()
  await page.locator('.bulk-actions').getByRole('button', { name: 'В избранное', exact: true }).click()
  await navigate(page, /^Избранное/)
  await expect(page.locator('.supplier-table tbody tr')).toHaveCount(2)
  await page.getByRole('checkbox', { name: 'Выбрать поставщиков на странице' }).check()
  await page.locator('.bulk-actions').getByRole('button', { name: 'Сравнить', exact: true }).click()
  await expect(page.locator('.comparison thead th')).toHaveCount(3)
  await navigate(page, /Возможности проекта/)
  await expect(page.locator('.scope-card')).toHaveCount(12)
  await expect(page.locator('.scope-card').filter({ hasText: 'Внешний поиск' })).toContainText('Не подключено')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать чек-лист', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('food-supplier-finder-checklist.md')
  await navigate(page, /Источники и интеграции/)
  await expect(page.locator('.sources-table tbody tr')).toHaveCount(12)
})

test('edit commercial terms and documents while preserving the original source', async ({ page }) => {
  const name = `Управление карточкой ${Date.now()}`
  const url = `https://editor-${Date.now()}.ru`
  await page.goto('./')
  await page.locator('.heading-actions').getByRole('button', { name: 'Добавить поставщика', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название компании').fill(name)
  await dialog.getByLabel('URL источника').fill(url + '/contacts')
  await dialog.getByLabel('Официальный сайт').fill(url)
  await dialog.getByLabel('Город', { exact: true }).fill('Екатеринбург')
  await dialog.getByRole('button', { name: 'Добавить товар', exact: true }).click()
  await dialog.getByLabel('Название товара 1').fill('Моцарелла')
  await dialog.getByLabel('Цена товара 1').fill('600')
  await dialog.getByRole('button', { name: 'Добавить документ', exact: true }).click()
  await dialog.getByLabel('Название документа', { exact: true }).fill('Тестовый документ')
  await dialog.getByLabel('URL документа', { exact: true }).fill(url + '/documents')
  await dialog.getByRole('button', { name: 'Добавить в каталог', exact: true }).click()
  await page.getByRole('textbox', { name: 'Товар или компания' }).fill(name)
  await expect(page.getByRole('button', { name, exact: true })).toHaveCount(1)
  await page.getByRole('button', { name, exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Редактировать', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Город', { exact: true }).fill('Казань')
  await page.getByRole('dialog').getByLabel('Цена товара 1').fill('650')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить изменения', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Казань')
  await page.getByRole('tab', { name: 'Условия и доставка', exact: true }).click()
  await expect(page.getByRole('dialog').locator('.terms-table')).toContainText('650')
  await expect(page.getByRole('dialog')).toContainText('Тестовый документ')
  await page.getByRole('tab', { name: 'Источники', exact: true }).click()
  await page.getByText('Предыдущие значения до изменения', { exact: true }).click()
  await expect(page.getByRole('dialog').locator('.source-history')).toContainText('Екатеринбург')
})
